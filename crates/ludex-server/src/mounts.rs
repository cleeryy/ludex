//! Mount-aware library roots (#290).
//!
//! The decision logic lives in [`ludex_core::mount`] so the server and the
//! desktop share one implementation and one fixture suite. This module adds
//! the process I/O (`/proc/self/mountinfo`, `/etc/fstab`, systemd units,
//! `systemctl`/`mount`) and the server-side free-space preflight used by
//! uploads and the extracted cache.
//!
//! Nothing here runs in tests except through [`FixtureProbe`]: no real mount,
//! fstab or systemctl is touched.

use std::path::Path;

use ludex_core::mount::{
    check_free_space, preflight_requirement, AutomountKind, AutomountPlan, FreeSpaceShortfall,
    MountIdentity,
};

use crate::error::ApiError;

pub use ludex_core::mount::{ensure, is_online, EnsuredMount, MountStatus, SystemProbe};

/// Alias kept for the scanner vocabulary: the state of a library root.
pub type RootMountStatus = MountStatus;

/// Real probe: `/proc/self/mountinfo`, `/etc/fstab`, systemd unit files and
/// `systemctl`/`mount`.
#[derive(Debug, Default, Clone, Copy)]
pub struct HostProbe;

impl SystemProbe for HostProbe {
    fn mountinfo(&self) -> Result<String, String> {
        std::fs::read_to_string("/proc/self/mountinfo")
            .map_err(|error| format!("could not read /proc/self/mountinfo: {error}"))
    }

    fn fstab(&self) -> String {
        std::fs::read_to_string("/etc/fstab").unwrap_or_default()
    }

    fn automount_units(&self) -> Vec<String> {
        let mut units = Vec::new();
        // Units generated by systemd-fstab-generator and hand-written units.
        for directory in [
            "/run/systemd/generator",
            "/run/systemd/system",
            "/etc/systemd/system",
        ] {
            let Ok(entries) = std::fs::read_dir(directory) else {
                continue;
            };
            for entry in entries.flatten() {
                let name = entry.file_name().to_string_lossy().to_string();
                if name.ends_with(".automount") && !units.contains(&name) {
                    units.push(name);
                }
            }
        }
        if units.is_empty() {
            if let Ok(output) = std::process::Command::new("systemctl")
                .args([
                    "list-unit-files",
                    "--type=automount",
                    "--no-legend",
                    "--plain",
                ])
                .output()
            {
                if output.status.success() {
                    for line in String::from_utf8_lossy(&output.stdout).lines() {
                        if let Some(name) = line.split_whitespace().next() {
                            if name.ends_with(".automount") && !units.contains(&name.to_string()) {
                                units.push(name.to_string());
                            }
                        }
                    }
                }
            }
        }
        units
    }

    fn run_plan(&self, plan: &AutomountPlan) -> Result<(), String> {
        let (program, argument) = match plan.kind {
            AutomountKind::SystemdUnit => (
                "systemctl",
                plan.unit
                    .clone()
                    .unwrap_or_else(|| plan.mount_point.clone()),
            ),
            AutomountKind::FstabMount => ("mount", plan.mount_point.clone()),
        };
        let output = std::process::Command::new(program)
            .arg(&argument)
            .output()
            .map_err(|error| format!("could not run {program} {argument}: {error}"))?;
        if output.status.success() {
            Ok(())
        } else {
            let detail = String::from_utf8_lossy(&output.stderr).trim().to_string();
            Err(format!("{program} {argument} failed: {detail}"))
        }
    }

    fn path_exists(&self, path: &Path) -> bool {
        path.is_dir()
    }

    fn identity(&self, path: &Path) -> Option<MountIdentity> {
        let mut current = Some(path);
        let mut existing = None;
        while let Some(candidate) = current {
            if candidate.exists() {
                existing = Some(candidate.to_path_buf());
                break;
            }
            current = candidate.parent();
        }
        let existing = existing?;
        let metadata = std::fs::metadata(&existing).ok()?;
        let marker = metadata
            .modified()
            .ok()
            .and_then(|time| time.duration_since(std::time::UNIX_EPOCH).ok())
            .map(|duration| i64::try_from(duration.as_secs()).unwrap_or(i64::MAX));
        Some(MountIdentity {
            #[cfg(unix)]
            device_id: {
                use std::os::unix::fs::MetadataExt;
                metadata.dev()
            },
            #[cfg(not(unix))]
            device_id: 0,
            marker,
        })
    }
}

/// Bytes available under `path`, resolved through its nearest existing parent.
#[must_use]
pub fn available_space(path: &Path) -> Option<u64> {
    let mut current = Some(path);
    while let Some(candidate) = current {
        if candidate.exists() {
            return fs2::available_space(candidate).ok();
        }
        current = candidate.parent();
    }
    None
}

/// Pre-flight of a write into a library (#290): `required_bytes` plus the
/// root's floor must fit, or the request is refused before the first byte.
///
/// An unreadable free-space figure never blocks: the OS still refuses the
/// write and the existing out-of-space paths keep the partial file.
pub fn check_capacity(
    directory: &Path,
    required_bytes: u64,
    min_free_bytes: u64,
) -> Result<(), FreeSpaceShortfall> {
    let Some(free) = available_space(directory) else {
        return Ok(());
    };
    check_free_space(free, required_bytes, min_free_bytes)
}

/// [`check_capacity`] as an API error (507) carrying the missing gigabytes.
#[must_use]
pub fn capacity_error(directory: &Path, shortfall: &FreeSpaceShortfall) -> ApiError {
    ApiError::new(
        axum::http::StatusCode::INSUFFICIENT_STORAGE,
        "insufficient_space",
        shortfall.message(directory),
    )
}

/// Full preflight for an archive landing in `directory`.
pub fn preflight(
    directory: &Path,
    archive_bytes: u64,
    min_free_bytes: u64,
) -> Result<(), ApiError> {
    check_capacity(
        directory,
        preflight_requirement(archive_bytes),
        min_free_bytes,
    )
    .map_err(|shortfall| capacity_error(directory, &shortfall))
}

#[cfg(test)]
mod tests {
    use super::*;
    use ludex_core::mount::{AutomountPlan, MountEntry};

    /// Injected probe: fixture mount table and fstab, no OS call.
    struct Probe {
        mountinfo: String,
        fstab: String,
        units: Vec<String>,
        existing: Vec<&'static str>,
    }

    impl SystemProbe for Probe {
        fn mountinfo(&self) -> Result<String, String> {
            Ok(self.mountinfo.clone())
        }

        fn fstab(&self) -> String {
            self.fstab.clone()
        }

        fn automount_units(&self) -> Vec<String> {
            self.units.clone()
        }

        fn run_plan(&self, _plan: &AutomountPlan) -> Result<(), String> {
            Ok(())
        }

        fn path_exists(&self, path: &Path) -> bool {
            self.existing.iter().any(|known| Path::new(known) == path)
        }

        fn identity(&self, _path: &Path) -> Option<MountIdentity> {
            Some(MountIdentity {
                device_id: 42,
                marker: Some(7),
            })
        }
    }

    const MOUNTED: &str = "23 1 259:1 / / rw shared:1 - ext4 /dev/nvme0n1p2 rw
45 23 0:35 / /mnt/nas rw shared:22 - nfs4 nas.local:/export rw";

    #[test]
    fn the_server_uses_the_shared_ensure_decision() {
        let probe = Probe {
            mountinfo: MOUNTED.to_string(),
            fstab: String::new(),
            units: Vec::new(),
            existing: vec!["/mnt/nas"],
        };
        let ensured = ensure(&probe, Path::new("/mnt/nas"));
        assert!(ensured.status.is_online());
        assert_eq!(ensured.status.mount_point(), Some("/mnt/nas"));
        assert!(is_online(&probe, Path::new("/mnt/nas")));
        let mounts: Vec<MountEntry> = ludex_core::mount::parse_mountinfo(MOUNTED);
        assert!(!ludex_core::mount::on_root_filesystem(
            &mounts,
            Path::new("/mnt/nas")
        ));
        assert!(ludex_core::mount::select_mount(&mounts, Path::new("/mnt/nas")).is_some());
    }

    #[test]
    fn the_preflight_refuses_below_the_floor_with_the_missing_gigabytes() {
        // A temporary directory always has *some* free space; build the check
        // from a requirement that is certainly too large.
        let shortfall = check_capacity(Path::new("/"), u64::MAX / 2, 5 << 30).unwrap_err();
        assert!(shortfall.missing_bytes > 0);
        let message = shortfall.message(Path::new("/mnt/nas"));
        assert!(message.contains("free-space floor"));
        let error = capacity_error(Path::new("/mnt/nas"), &shortfall);
        assert_eq!(error.status, axum::http::StatusCode::INSUFFICIENT_STORAGE);
        assert_eq!(error.code, "insufficient_space");
    }

    #[test]
    fn a_small_requirement_passes() {
        assert!(check_capacity(Path::new("/"), 1, 0).is_ok());
    }
}
