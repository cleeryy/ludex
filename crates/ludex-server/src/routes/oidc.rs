/// OIDC and desktop handoff routes.
pub fn router() -> Router<AppState> {
    Router::new()
        .route("/auth/oidc/start", get(start))
        .route("/auth/oidc/callback", get(callback))
        .route("/auth/oidc/exchange", post(exchange))
        .route("/auth/desktop-handoff", post(desktop_handoff))
        .route("/auth/desktop-handoff/claim", post(claim_handoff))
}

#[derive(Debug, Default, Deserialize)]
struct CallbackQuery {
    #[serde(default)]
    code: Option<String>,
    #[serde(default)]
    state: Option<String>,
    #[serde(default)]
    error: Option<String>,
    #[serde(default)]
    error_description: Option<String>,
}

#[derive(Debug, Deserialize, utoipa::ToSchema)]
#[serde(rename_all = "camelCase")]
pub struct OidcExchangeRequest {
    code: String,
}

/// `POST /api/auth/desktop-handoff` body (#157).
#[derive(Debug, Deserialize, utoipa::ToSchema)]
#[serde(rename_all = "camelCase")]
pub struct DesktopHandoffRequest {
    /// Random state generated by the desktop app.
    pub state: String,
}

/// Handoff creation response. Never contains the code or a token.
#[derive(Debug, Serialize, utoipa::ToSchema)]
#[serde(rename_all = "camelCase")]
pub struct DesktopHandoffResponse {
    /// When the pending handoff (and its code) stops working.
    pub expires_at: DateTime<Utc>,
}

/// `POST /api/auth/desktop-handoff/claim` body (#157).
#[derive(Debug, Deserialize, utoipa::ToSchema)]
#[serde(rename_all = "camelCase")]
pub struct DesktopHandoffClaimRequest {
    /// The same state the desktop generated for this attempt.
    pub state: String,
}

/// Claim response: one-time code, redeemable at `/api/auth/oidc/exchange`.
#[derive(Debug, Serialize, utoipa::ToSchema)]
#[serde(rename_all = "camelCase")]
pub struct DesktopHandoffClaimResponse {
    /// Single-use exchange code. Not a token.
    pub code: String,
    /// When the code stops working.
    pub expires_at: DateTime<Utc>,
}

async fn start(State(state): State<AppState>, headers: HeaderMap) -> Result<Response, ApiError> {
    let client = state.oidc_client().await.ok_or_else(oidc_disabled)?;
    let url = client.begin(&headers).await?;
    let mut response = Redirect::to(&url).into_response();
    response
        .headers_mut()
        .insert(header::CACHE_CONTROL, HeaderValue::from_static("no-store"));
    Ok(response)
}

async fn callback(
    State(state): State<AppState>,
    ApiQuery(query): ApiQuery<CallbackQuery>,
) -> Result<Response, ApiError> {
    let client = state.oidc_client().await.ok_or_else(oidc_disabled)?;
    if let Some(error) = query.error {
        let message = query
            .error_description
            .filter(|description| !description.trim().is_empty())
            .unwrap_or_else(|| format!("The identity provider rejected the login: {error}"));
        return Err(ApiError::bad_request("oidc_provider_error", message));
    }
    let code = query
        .code
        .as_deref()
        .map(str::trim)
        .filter(|code| !code.is_empty())
        .ok_or_else(|| ApiError::bad_request("invalid_request", "Missing authorization code"))?;
    let state_param = query
        .state
        .as_deref()
        .map(str::trim)
        .filter(|state| !state.is_empty())
        .ok_or_else(|| ApiError::bad_request("invalid_state", "Missing SSO state"))?;

    let identity = client.complete(code, state_param).await?;
    let user_id = oidc::provision_user(&state, &client, &identity).await?;
    let one_time_code = state.exchange_codes.issue(user_id, EXCHANGE_CODE_TTL)?;
    let location = client.callback_location(&one_time_code);

    let mut response = Redirect::to(&location).into_response();
    response
        .headers_mut()
        .insert(header::CACHE_CONTROL, HeaderValue::from_static("no-store"));
    Ok(response)
}

async fn exchange(
    State(state): State<AppState>,
    JsonBody(request): JsonBody<OidcExchangeRequest>,
) -> Result<Response, ApiError> {
    // Redeeming a code only exists for SSO sessions; keep answering exactly as
    // before when the provider is not configured.
    state.oidc_client().await.ok_or_else(oidc_disabled)?;
    let code = request.code.trim();
    if code.is_empty() {
        return Err(ApiError::bad_request(
            "invalid_request",
            "Missing SSO exchange code",
        ));
    }
    let user_id = state.exchange_codes.take(code).ok_or_else(|| {
        ApiError::new(
            StatusCode::UNAUTHORIZED,
            "invalid_oidc_code",
            "The SSO code is invalid, expired or already used",
        )
    })?;

    let row = db::query_as::<UserRow>(
        "SELECT id, username, password_hash, email, role, activated, avatar_path,
                age_limit, created_at, updated_at, oidc_issuer, oidc_subject,
                onboarding_completed_at, onboarding_step
         FROM users WHERE id = ?",
    )
    .bind(user_id)
    .fetch_optional(&state.pool)
    .await
    .map_err(ApiError::from)?
    .ok_or_else(|| {
        ApiError::new(
            StatusCode::UNAUTHORIZED,
            "invalid_oidc_code",
            "The SSO account is no longer available",
        )
    })?;
    if row.activated == 0 {
        return Err(ApiError::forbidden(
            "account_disabled",
            "This account is disabled",
        ));
    }

    let user = row.to_public();
    let info = crate::auth::SessionInfo {
        user_agent: None,
        ip: None,
    };
    let (issued, _session_id) =
        crate::auth::start_session(&state, user.id, user.role, &info).await?;
    let mut response = Json(AuthResponse {
        token: issued.token,
        user,
        expires_at: Some(issued.expires_at),
    })
    .into_response();
    response
        .headers_mut()
        .insert(header::CACHE_CONTROL, HeaderValue::from_static("no-store"));
    Ok(response)
}

/// Creates a handoff for the calling web session (#157).
///
/// The desktop app generated `state` and is polling the claim endpoint. This
/// endpoint binds the caller's account to that state and returns only the
/// expiry: the code travels exclusively through the claim response, and no JWT
/// ever appears in a URL, a log line or this payload.
async fn desktop_handoff(
    State(state): State<AppState>,
    ConnectInfo(peer): ConnectInfo<SocketAddr>,
    user: AuthUser,
    JsonBody(request): JsonBody<DesktopHandoffRequest>,
) -> Result<Json<DesktopHandoffResponse>, ApiError> {
    user.require_scope(Scope::Write)?;
    let limit_key = format!("handoff:{}", user.id);
    if let Err(wait) = state.handoff_create_limits.check(&limit_key) {
        return Err(ApiError::too_many_requests(
            "handoff_throttled",
            format!("Too many desktop sign-in attempts. Try again in {wait} seconds."),
        )
        .with_retry_after(wait));
    }
    desktop_handoff::validate_state(&request.state)?;

    // The handoff only exists to bring an SSO session to the desktop. Without a
    // provider there is nothing to hand off, and the exchange would refuse the
    // code anyway (same 404 as before).
    state.oidc_client().await.ok_or_else(oidc_disabled)?;

    let ttl = state.desktop_handoffs.ttl();
    let code = state.exchange_codes.issue(user.id, ttl)?;
    let expires_at = state
        .desktop_handoffs
        .insert(&request.state, user.id, &code)?;

    state.events.emit(
        Event::new(actions::OIDC_HANDOFF_CREATED, user.actor())
            .target("user", user.id.to_string())
            .metadata(json!({ "expiresAt": expiry_datetime(expires_at) }))
            .ip(Some(peer.ip())),
    );
    Ok(Json(DesktopHandoffResponse {
        expires_at: expiry_datetime(expires_at),
    }))
}

/// Claims a pending handoff exactly once (#157).
///
/// Unauthenticated by design: the desktop has no session yet. The 256-bit state
/// is the credential, it is consumed on success, and unknown, expired and
/// already-used states all answer the same `410` so the endpoint never reveals
/// whether a sign-in is pending or for whom.
async fn claim_handoff(
    State(state): State<AppState>,
    ConnectInfo(peer): ConnectInfo<SocketAddr>,
    JsonBody(request): JsonBody<DesktopHandoffClaimRequest>,
) -> Result<Response, ApiError> {
    let ip = peer.ip();
    let limit_key = format!("claim:{ip}");
    if let Err(wait) = state.handoff_claim_limits.check(&limit_key) {
        return Err(ApiError::too_many_requests(
            "handoff_throttled",
            format!("Too many desktop sign-in attempts. Try again in {wait} seconds."),
        )
        .with_retry_after(wait));
    }
    if let Err(error) = desktop_handoff::validate_state(&request.state) {
        state.events.emit(
            Event::new(actions::OIDC_HANDOFF_FAILED, Actor::System)
                .metadata(json!({ "reason": "invalid_state" }))
                .ip(Some(ip)),
        );
        return Err(error);
    }

    let Some(claimed) = state.desktop_handoffs.claim(&request.state) else {
        state.events.emit(
            Event::new(actions::OIDC_HANDOFF_FAILED, Actor::System)
                .metadata(json!({ "reason": "not_found" }))
                .ip(Some(ip)),
        );
        return Err(ApiError::new(
            StatusCode::GONE,
            "handoff_unavailable",
            "This sign-in handoff is unknown, expired or already used. Start again from Ludex.",
        ));
    };

    state.events.emit(
        Event::new(actions::OIDC_HANDOFF_CLAIMED, Actor::System)
            .target("user", claimed.user_id.to_string())
            .metadata(json!({ "expiresAt": expiry_datetime(claimed.expires_at) }))
            .ip(Some(ip)),
    );

    let mut response = Json(DesktopHandoffClaimResponse {
        code: claimed.code,
        expires_at: expiry_datetime(claimed.expires_at),
    })
    .into_response();
    response
        .headers_mut()
        .insert(header::CACHE_CONTROL, HeaderValue::from_static("no-store"));
    Ok(response)
}

fn oidc_disabled() -> ApiError {
    ApiError::not_found("oidc_disabled", "SSO is not configured on this server")
}
