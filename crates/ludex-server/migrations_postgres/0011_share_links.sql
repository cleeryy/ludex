-- Share links for a game or a single version (#9), PostgreSQL edition.

CREATE TABLE IF NOT EXISTS share_links (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token_hash       TEXT NOT NULL UNIQUE,
    game_id          BIGINT NOT NULL REFERENCES games(id) ON DELETE CASCADE,
    version_id       BIGINT REFERENCES game_versions(id) ON DELETE CASCADE,
    label            TEXT,
    created_by       BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    created_at       TEXT NOT NULL,
    expires_at       TEXT,
    password_hash    TEXT,
    max_downloads    BIGINT,
    download_count   BIGINT NOT NULL DEFAULT 0,
    revoked_at       TEXT,
    last_accessed_at TEXT
);

CREATE INDEX IF NOT EXISTS idx_share_links_game_id ON share_links(game_id);
CREATE INDEX IF NOT EXISTS idx_share_links_token_hash ON share_links(token_hash);
