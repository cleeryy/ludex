-- Media cache garbage collection (#18), PostgreSQL edition.

CREATE TABLE IF NOT EXISTS media_manifest (
    name        TEXT PRIMARY KEY,
    size        BIGINT NOT NULL DEFAULT 0,
    sha256      TEXT NOT NULL,
    created_at  TEXT NOT NULL,
    verified_at TEXT
);

CREATE TABLE IF NOT EXISTS media_gc_runs (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dry_run       BIGINT NOT NULL DEFAULT 1,
    scanned       BIGINT NOT NULL DEFAULT 0,
    referenced    BIGINT NOT NULL DEFAULT 0,
    orphan_files  BIGINT NOT NULL DEFAULT 0,
    orphan_bytes  BIGINT NOT NULL DEFAULT 0,
    deleted_files BIGINT NOT NULL DEFAULT 0,
    deleted_bytes BIGINT NOT NULL DEFAULT 0,
    started_at    TEXT NOT NULL,
    finished_at   TEXT
);

CREATE INDEX IF NOT EXISTS idx_media_gc_runs_started
    ON media_gc_runs(started_at DESC, id DESC);
