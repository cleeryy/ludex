-- Community phase 2 (#161): friendships, presence and in-app notifications,
-- PostgreSQL edition. Timestamps are RFC 3339 UTC text, like the rest of the
-- schema, so both engines return identical shapes.

ALTER TABLE users ADD COLUMN presence_enabled BIGINT NOT NULL DEFAULT 0;
ALTER TABLE users ADD COLUMN friends_activity BIGINT NOT NULL DEFAULT 0;

CREATE TABLE IF NOT EXISTS friendships (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    requester_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    addressee_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    pair_key     TEXT NOT NULL,
    status       TEXT NOT NULL DEFAULT 'pending'
                 CHECK (status IN ('pending', 'accepted')),
    created_at   TEXT NOT NULL,
    updated_at   TEXT NOT NULL,
    CHECK (requester_id <> addressee_id)
);

CREATE UNIQUE INDEX IF NOT EXISTS idx_friendships_pair ON friendships(pair_key);
CREATE INDEX IF NOT EXISTS idx_friendships_requester
    ON friendships(requester_id, status, id DESC);
CREATE INDEX IF NOT EXISTS idx_friendships_addressee
    ON friendships(addressee_id, status, id DESC);

CREATE TABLE IF NOT EXISTS user_blocks (
    blocker_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    blocked_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    created_at TEXT NOT NULL,
    PRIMARY KEY (blocker_id, blocked_id),
    CHECK (blocker_id <> blocked_id)
);

CREATE INDEX IF NOT EXISTS idx_user_blocks_blocked ON user_blocks(blocked_id);

CREATE TABLE IF NOT EXISTS presence (
    user_id    BIGINT PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
    state      TEXT NOT NULL CHECK (state IN ('online', 'in_game')),
    game_id    BIGINT REFERENCES games(id) ON DELETE SET NULL,
    updated_at TEXT NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_presence_updated ON presence(updated_at DESC);

CREATE TABLE IF NOT EXISTS notifications (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id        BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    kind           TEXT NOT NULL
                   CHECK (kind IN ('friend_request', 'friend_accepted',
                                   'friend_achievement', 'collection_share')),
    actor_id       BIGINT REFERENCES users(id) ON DELETE CASCADE,
    game_id        BIGINT REFERENCES games(id) ON DELETE SET NULL,
    achievement_id BIGINT REFERENCES achievements(id) ON DELETE SET NULL,
    payload        TEXT NOT NULL DEFAULT '{}',
    created_at     TEXT NOT NULL,
    read_at        TEXT
);

CREATE INDEX IF NOT EXISTS idx_notifications_user ON notifications(user_id, id DESC);
CREATE INDEX IF NOT EXISTS idx_notifications_unread
    ON notifications(user_id, read_at);

CREATE TABLE IF NOT EXISTS notification_prefs (
    user_id             BIGINT PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
    friend_requests     BIGINT NOT NULL DEFAULT 1,
    friend_accepted     BIGINT NOT NULL DEFAULT 1,
    friend_achievements BIGINT NOT NULL DEFAULT 0,
    collection_shares   BIGINT NOT NULL DEFAULT 1,
    updated_at          TEXT NOT NULL
);
