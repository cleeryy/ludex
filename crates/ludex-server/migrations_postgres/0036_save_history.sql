-- Save manager history (#295), PostgreSQL edition.
--
-- Same columns as `0036_save_history.sql`. `pinned` is BIGINT on purpose: the
-- Rust row decoder reads i64 on both engines and converts to bool, and sqlx
-- refuses an INT4 -> i64 decode. Keeping the newest snapshot and every pinned
-- one out of the automatic retention pass protects the last known-good copy.

ALTER TABLE save_snapshots ADD COLUMN IF NOT EXISTS pinned BIGINT NOT NULL DEFAULT 0;

CREATE TABLE IF NOT EXISTS save_restore_receipts (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    game_id     BIGINT NOT NULL REFERENCES games(id) ON DELETE CASCADE,
    snapshot_id BIGINT NOT NULL REFERENCES save_snapshots(id) ON DELETE CASCADE,
    device_id   TEXT,
    kind        TEXT NOT NULL DEFAULT 'server',
    restored_at TEXT NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_save_restore_receipts_user_game
    ON save_restore_receipts(user_id, game_id, restored_at DESC);

CREATE INDEX IF NOT EXISTS idx_save_snapshots_pinned
    ON save_snapshots(user_id, game_id, pinned);
