-- Multiple library roots (#45), folder watcher (#44), integrity checks (#43).
--
-- The SQLite migration rebuilds `game_versions` to scope file paths per root.
-- PostgreSQL has no live rows when this schema is first created, so the same
-- end state is reached with plain ALTER TABLE statements (row ids are
-- preserved, which `save_snapshots.version_id` depends on).

CREATE TABLE IF NOT EXISTS library_roots (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    label        TEXT NOT NULL,
    path         TEXT NOT NULL,
    enabled      BIGINT NOT NULL DEFAULT 1,
    available    BIGINT NOT NULL DEFAULT 1,
    position     BIGINT NOT NULL DEFAULT 0,
    created_at   TEXT NOT NULL,
    updated_at   TEXT NOT NULL,
    last_scan_at TEXT,
    last_error   TEXT
);

CREATE UNIQUE INDEX IF NOT EXISTS idx_library_roots_path ON library_roots(path);
CREATE INDEX IF NOT EXISTS idx_library_roots_position ON library_roots(position, id);

INSERT INTO library_roots (label, path, enabled, available, position, created_at, updated_at)
SELECT 'Library', '', 1, 1, 0,
       to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS"Z"'),
       to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS"Z"')
WHERE NOT EXISTS (SELECT 1 FROM library_roots);

ALTER TABLE games ADD COLUMN root_id BIGINT REFERENCES library_roots(id) ON DELETE SET NULL;

ALTER TABLE game_versions ADD COLUMN root_id BIGINT REFERENCES library_roots(id) ON DELETE SET NULL;
ALTER TABLE game_versions ADD COLUMN root_unavailable BIGINT NOT NULL DEFAULT 0;
ALTER TABLE game_versions ADD COLUMN content_hash TEXT;

ALTER TABLE game_versions DROP CONSTRAINT IF EXISTS game_versions_file_path_key;
ALTER TABLE game_versions ADD CONSTRAINT game_versions_root_path_key UNIQUE (root_id, file_path);

CREATE INDEX IF NOT EXISTS idx_game_versions_game_id ON game_versions(game_id);
CREATE INDEX IF NOT EXISTS idx_game_versions_missing ON game_versions(missing);
CREATE INDEX IF NOT EXISTS idx_game_versions_root ON game_versions(root_id, missing);

CREATE TABLE IF NOT EXISTS integrity_reports (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    scope          TEXT NOT NULL DEFAULT 'all',
    status         TEXT NOT NULL DEFAULT 'running',
    checked        BIGINT NOT NULL DEFAULT 0,
    findings_count BIGINT NOT NULL DEFAULT 0,
    error          TEXT,
    started_at     TEXT NOT NULL,
    finished_at    TEXT
);

CREATE INDEX IF NOT EXISTS idx_integrity_reports_started
    ON integrity_reports(started_at DESC, id DESC);

CREATE TABLE IF NOT EXISTS integrity_findings (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    report_id   BIGINT NOT NULL REFERENCES integrity_reports(id) ON DELETE CASCADE,
    kind        TEXT NOT NULL,
    target_type TEXT NOT NULL,
    target_id   TEXT,
    path        TEXT,
    detail      TEXT,
    created_at  TEXT NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_integrity_findings_report
    ON integrity_findings(report_id, id);
