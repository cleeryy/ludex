-- Core gaming additions (#51, #52, #28), PostgreSQL edition.
--
-- Same tables and columns as `0019_core_gaming.sql`. Emulator names are
-- case-insensitively unique: SQLite uses `COLLATE NOCASE UNIQUE`, PostgreSQL
-- uses a unique expression index on `lower(name)`.

CREATE TABLE IF NOT EXISTS emulators (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name           TEXT NOT NULL,
    command        TEXT NOT NULL,
    platforms_json TEXT NOT NULL DEFAULT '[]',
    enabled        BIGINT NOT NULL DEFAULT 1,
    created_at     TEXT NOT NULL,
    updated_at     TEXT NOT NULL
);

CREATE UNIQUE INDEX IF NOT EXISTS idx_emulators_name
    ON emulators(lower(name));

CREATE TABLE IF NOT EXISTS emulator_defaults (
    platform    TEXT PRIMARY KEY,
    emulator_id BIGINT NOT NULL REFERENCES emulators(id) ON DELETE CASCADE,
    created_at  TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS controller_profiles (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    -- 0 is the account-wide profile; anything else is a per-game override.
    game_id      BIGINT NOT NULL DEFAULT 0,
    name         TEXT NOT NULL,
    profile_json TEXT NOT NULL,
    created_at   TEXT NOT NULL,
    updated_at   TEXT NOT NULL,
    UNIQUE (user_id, game_id)
);

CREATE INDEX IF NOT EXISTS idx_controller_profiles_user
    ON controller_profiles(user_id);

ALTER TABLE library_roots ADD COLUMN kind TEXT NOT NULL DEFAULT 'game';
ALTER TABLE games ADD COLUMN kind TEXT NOT NULL DEFAULT 'game';
ALTER TABLE games ADD COLUMN platform TEXT;
ALTER TABLE games ADD COLUMN emulator_id BIGINT REFERENCES emulators(id) ON DELETE SET NULL;

CREATE INDEX IF NOT EXISTS idx_games_kind_platform ON games(kind, platform);
