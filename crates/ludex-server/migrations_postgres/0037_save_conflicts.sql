-- Save conflict policy for multi-device play (#296), PostgreSQL edition.
--
-- Same columns and tables as `0037_save_conflicts.sql`. BIGINT columns match
-- the i64 row decoders sqlx uses for both engines.

ALTER TABLE save_snapshots ADD COLUMN client_mtime TEXT;
ALTER TABLE save_snapshots ADD COLUMN clock_offset_secs BIGINT NOT NULL DEFAULT 0;
ALTER TABLE save_snapshots ADD COLUMN save_seq BIGINT;
ALTER TABLE save_snapshots ADD COLUMN conflict_of BIGINT REFERENCES save_snapshots(id) ON DELETE SET NULL;

CREATE INDEX IF NOT EXISTS idx_save_snapshots_latest
    ON save_snapshots(user_id, game_id, conflict_of, created_at DESC);

CREATE TABLE IF NOT EXISTS save_devices (
    user_id           BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    device_id         TEXT   NOT NULL,
    label             TEXT,
    clock_offset_secs BIGINT NOT NULL DEFAULT 0,
    first_seen_at     TEXT   NOT NULL,
    last_seen_at      TEXT   NOT NULL,
    PRIMARY KEY (user_id, device_id)
);

CREATE TABLE IF NOT EXISTS save_conflicts (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id               BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    game_id               BIGINT NOT NULL REFERENCES games(id) ON DELETE CASCADE,
    existing_snapshot_id  BIGINT NOT NULL REFERENCES save_snapshots(id) ON DELETE CASCADE,
    candidate_snapshot_id BIGINT NOT NULL REFERENCES save_snapshots(id) ON DELETE CASCADE,
    reason                TEXT   NOT NULL,
    status                TEXT   NOT NULL DEFAULT 'open',
    detected_at           TEXT   NOT NULL,
    resolved_at           TEXT,
    strategy              TEXT,
    UNIQUE (existing_snapshot_id, candidate_snapshot_id)
);

CREATE INDEX IF NOT EXISTS idx_save_conflicts_open
    ON save_conflicts(user_id, game_id, status, detected_at DESC);

CREATE TABLE IF NOT EXISTS save_sync_policies (
    user_id          BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    game_id          BIGINT NOT NULL REFERENCES games(id) ON DELETE CASCADE,
    prefer_device_id TEXT,
    updated_at       TEXT   NOT NULL,
    PRIMARY KEY (user_id, game_id)
);
