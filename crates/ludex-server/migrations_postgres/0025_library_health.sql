-- Library Health Center (#165), PostgreSQL edition.
--
-- Same tables as `0021_library_health.sql`: a cached report plus typed findings.
-- Identifiers use BIGINT identity columns; SQLite uses AUTOINCREMENT.

CREATE TABLE IF NOT EXISTS library_health_reports (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    status         TEXT NOT NULL DEFAULT 'running',
    trigger        TEXT NOT NULL DEFAULT 'manual',
    progress       BIGINT NOT NULL DEFAULT 0,
    total          BIGINT NOT NULL DEFAULT 0,
    findings_count BIGINT NOT NULL DEFAULT 0,
    errors_count   BIGINT NOT NULL DEFAULT 0,
    warnings_count BIGINT NOT NULL DEFAULT 0,
    info_count     BIGINT NOT NULL DEFAULT 0,
    error          TEXT,
    started_at     TEXT NOT NULL,
    finished_at    TEXT
);

CREATE INDEX IF NOT EXISTS idx_library_health_reports_status
    ON library_health_reports(status, id DESC);

CREATE TABLE IF NOT EXISTS library_health_findings (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    report_id     BIGINT NOT NULL REFERENCES library_health_reports(id) ON DELETE CASCADE,
    category      TEXT NOT NULL,
    kind          TEXT NOT NULL,
    severity      TEXT NOT NULL,
    game_id       BIGINT,
    version_id    BIGINT,
    root_id       BIGINT,
    path          TEXT,
    title         TEXT NOT NULL,
    detail        TEXT NOT NULL,
    evidence_json TEXT NOT NULL DEFAULT '{}',
    actions_json  TEXT NOT NULL DEFAULT '[]',
    created_at    TEXT NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_library_health_findings_report
    ON library_health_findings(report_id, severity, id);
CREATE INDEX IF NOT EXISTS idx_library_health_findings_category
    ON library_health_findings(report_id, category);
