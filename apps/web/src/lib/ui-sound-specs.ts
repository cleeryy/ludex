/* --------------------------------- prefs ---------------------------------- */

export interface SoundPrefs {
  enabled: boolean;
  /** 0–1; applied as `gain = volume²`, so 45 % sits near half loudness. */
  volume: number;
}

/** Sound on at 45 %: audible at three metres without becoming an event. */
export const DEFAULT_SOUND_PREFS: SoundPrefs = { enabled: true, volume: 0.45 };

/** The volume slider and the settings row step in 5 % increments. */
export const VOLUME_STEP = 0.05;

export function clampVolume(value: unknown): number {
  if (typeof value !== "number" || !Number.isFinite(value)) return DEFAULT_SOUND_PREFS.volume;
  return Math.min(1, Math.max(0, value));
}

/** One slider step (5 %), clamped to 0–1 and kept on two decimals. */
export function stepVolume(volume: number, delta: 1 | -1): number {
  return Math.min(1, Math.max(0, Math.round((clampVolume(volume) + delta * VOLUME_STEP) * 100) / 100));
}

/** Missing or hand-edited JSON keeps working: every field falls back alone. */
export function sanitizeSoundPrefs(value: unknown): SoundPrefs {
  if (!value || typeof value !== "object") return { ...DEFAULT_SOUND_PREFS };
  const record = value as Record<string, unknown>;
  return {
    enabled: typeof record.enabled === "boolean" ? record.enabled : DEFAULT_SOUND_PREFS.enabled,
    volume: clampVolume(record.volume),
  };
}

/** Linear gain for a cue: its own trim times the squared master volume. */
export function cueGain(spec: CueSpec, volume: number): number {
  return Math.pow(10, spec.gainDb / 20) * clampVolume(volume) ** 2;
}
