/* --------------------------------------------------------------------------
   Big Picture sound model (#198).

   The cue table is the single source of truth for what the manager plays, how
   loud it is and which cue survives reduced motion. The WAVs next to it are
   generated by `apps/web/scripts/bp-sounds.mjs` from the same parameters and
   verified by `ui-sound-specs.test.ts` (format, length, peak, budget), so the
   table cannot drift from the committed audio.

   Sound language: "dry archive" — a short transient plus one pitched body.
   Mono, 48 kHz, 16-bit; 45–700 ms; never more than three partials at once;
   movement at -20 dBFS peak, confirmation at -12, nothing above -10.

   `achievement` and `notification` ship and are tested with the rest, but the
   surfaces that fire them (the achievements app, unread notifications) land in
   a later slice, so nothing fabricates a trigger for them today.
   -------------------------------------------------------------------------- */

/** Every sound Big Picture can make. Generated once, shipped as a WAV. */
export type CueId =
  | "move"
  | "confirm"
  | "back"
  | "openGroup"
  | "closeGroup"
  | "tabChange"
  | "error"
  | "launch"
  | "achievement"
  | "installComplete"
  | "power"
  | "overlayOpen"
  | "overlayClose"
  | "notification";

export interface CueSpec {
  /** File name inside `public/sounds/bp/`. */
  file: string;
  /** Mix trim applied on top of the file's own peak (0 today). */
  gainDb: number;
  /** Voices of this cue allowed at once; the oldest is dropped. */
  maxVoices: number;
  /** Kept under reduced motion: functional feedback never disappears. */
  essential: boolean;
  /** Two starts closer than this are the same event (move dedupes at 24 ms). */
  minGapMs: number;
  durationMs: number;
  /** Normalisation target of the generated file, in dBFS. */
  peakDb: number;
  /** Pitched partials, for review and for the three-partial ceiling. */
  partials: readonly number[];
}

