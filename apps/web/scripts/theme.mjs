#!/usr/bin/env node
/**
 * Theme stylesheet generator (#140).
 *
 * `src/theme/themes.json` is the single source of truth for the built-in
 * palettes. This script validates it and writes the static fallback stylesheet
 * (`src/styles/themes.generated.css`) used before the boot script runs, on a
 * first visit with no stored preference, and when JavaScript is unavailable.
 *
 *   node scripts/theme.mjs            # check that the stylesheet is current (CI)
 *   node scripts/theme.mjs --write    # regenerate it
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const webRoot = path.resolve(here, "..");
const registryPath = path.join(webRoot, "src/theme/themes.json");
const outputPath = path.join(webRoot, "src/styles/themes.generated.css");
const write = process.argv.includes("--write");

const TOKENS = [
  "bg",
  "bg-deep",
  "surface",
  "surface-2",
  "elevated",
  "line",
  "line-2",
  "ink",
  "ink-2",
  "ink-3",
  "signal",
  "on-signal",
  "signal-text",
  "signal-line",
  "danger",
  "ok",
  "warn",
  "focus",
  "stage",
  "stage-ink",
  "stage-ink-2",
  "stage-ok",
  "scrim",
  "shadow",
  "sheen",
  "grain-opacity",
];

function fail(message) {
  console.error(`theme: ${message}`);
  process.exit(1);
}

let registry;
try {
  registry = JSON.parse(fs.readFileSync(registryPath, "utf8"));
} catch (cause) {
  fail(`cannot read src/theme/themes.json: ${cause.message}`);
}

if (!Array.isArray(registry.themes) || registry.themes.length < 4) {
  fail("expected at least four built-in themes");
}
if (!registry.themes.some((theme) => theme.id === registry.default)) {
  fail(`default theme ${JSON.stringify(registry.default)} is not in the registry`);
}

const ids = new Set();
for (const theme of registry.themes) {
  if (!theme.id || ids.has(theme.id)) fail(`duplicate or missing theme id ${JSON.stringify(theme.id)}`);
  ids.add(theme.id);
  if (theme.mode !== "dark" && theme.mode !== "light") fail(`${theme.id}: mode must be dark or light`);
  const keys = Object.keys(theme.tokens ?? {}).sort();
  const expected = [...TOKENS].sort();
  if (keys.length !== expected.length || keys.some((key, index) => key !== expected[index])) {
    fail(`${theme.id}: token set differs from the contract (${keys.join(", ")})`);
  }
  for (const token of TOKENS) {
    const value = theme.tokens[token];
    if (typeof value !== "string" || value.trim() === "") fail(`${theme.id}: ${token} is empty`);
    if (token === "grain-opacity") {
      const numeric = Number(value);
      if (!Number.isFinite(numeric) || numeric < 0 || numeric > 0.2) fail(`${theme.id}: invalid grain-opacity`);
      continue;
    }
    if (!/^#(?:[0-9a-fA-F]{3}|[0-9a-fA-F]{6})$/.test(value)) fail(`${theme.id}: ${token} is not a hex colour`);
  }
}

function block(selector, theme) {
  const lines = TOKENS.map((token) => `  --${token}: ${theme.tokens[token]};`);
  lines.push(`  color-scheme: ${theme.mode};`);
  return `${selector} {\n${lines.join("\n")}\n}\n`;
}

const defaultTheme = registry.themes.find((theme) => theme.id === registry.default);
const blocks = [
  block(":root", defaultTheme),
  ...registry.themes.map((theme) => block(`[data-theme="${theme.id}"]`, theme)),
];

const css = `/* Generated by scripts/theme.mjs from src/theme/themes.json. Do not edit. */
${blocks.join("\n")}`;

if (write) {
  fs.writeFileSync(outputPath, css);
  console.log(`theme: wrote ${path.relative(webRoot, outputPath)} (${registry.themes.length} themes)`);
  process.exit(0);
}

const current = fs.existsSync(outputPath) ? fs.readFileSync(outputPath, "utf8") : "";
if (current !== css) {
  fail("src/styles/themes.generated.css is stale — run `pnpm --filter @ludex/web theme:write`");
}
console.log(`theme: ${registry.themes.length} built-in themes, stylesheet current`);
